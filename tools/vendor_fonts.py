"""
Vendors the web UI fonts into beetsplug/beetstreamnext/web/static/vendor/fonts/

    uv run tools/vendor_fonts.py            # (re)generate the files
    uv run tools/vendor_fonts.py --check    # fail if the committed files differ from a fresh build (for CI)
"""
from __future__ import annotations

import argparse
import hashlib
import io
import re
import sys
import urllib.parse
import urllib.request
from pathlib import Path
from typing import Optional, List

from fontTools import subset
from fontTools.ttLib import TTFont
from fontTools.varLib import instancer

##

ROOT = Path(__file__).resolve().parent.parent
PACKAGE = ROOT / 'beetsplug' / 'beetstreamnext'
OUT_DIR = PACKAGE / 'web' / 'static' / 'vendor' / 'fonts'
SCANNED = [PACKAGE / 'web' / 'templates', PACKAGE / 'web' / 'static' / 'js', PACKAGE / 'blueprints']

##

text_font_repo = 'rsms/inter'
text_font_url = f'https://raw.githubusercontent.com/{text_font_repo}'
text_font_commit = 'e3a3d4c57d5ecc01453a575621882a384c1995a3'

text_font_file = f'{text_font_url}/{text_font_commit}/docs/font-files/InterVariable.woff2'
text_font_SHA256 = '693b77d4f32ee9b8bfc995589b5fad5e99adf2832738661f5402f9978429a8e3'

text_font_license = f'{text_font_url}/{text_font_commit}/LICENSE.txt'

symbols_repo = 'google/material-design-icons'
symbols_url = f'https://raw.githubusercontent.com/{symbols_repo}'
symbols_pinned_commit = '49d4db35df873165d6bd6ba09b063c7dafbac2f4'

symbols_file = f'{symbols_url}/{symbols_pinned_commit}/variablefont/MaterialSymbolsOutlined[FILL,GRAD,opsz,wght].woff2'
symbols_SHA256 = '66187cd42fe1d24d3ea6be77da7466c4fc6c1cd1d0870b685e041d8402680063'

symbols_license = f'{symbols_url}/{symbols_pinned_commit}/LICENSE'


##

def download(url: str, sha256: Optional[str] = None) -> io.BytesIO:

    with urllib.request.urlopen(urllib.parse.quote(url, safe=':/,'), timeout=120) as resp:
        data = resp.read()

    digest = hashlib.sha256(data).hexdigest()

    if sha256 and digest != sha256:
        sys.exit(f'Checksum mismatch for {url}:\n  expected {sha256}\n  got      {digest}')

    return io.BytesIO(data)


def icons_used(all_names: List[str]) -> List[str]:

    known = set(all_names)
    found: set[str] = set()

    for root in SCANNED:
        for path in root.rglob('*'):
            if path.suffix in ('.html', '.js', '.py') and path.is_file() and '/vendor/' not in path.as_posix():
                text = path.read_text(encoding='utf-8', errors='ignore')
                found |= known & set(re.findall(r'''(?<=['">])[a-z][a-z0-9_]*(?=['"<])''', text))

    return sorted(found)


def subset_symbols(font_bytes: io.BytesIO, icons: List[str]) -> bytes:

    font = TTFont(font_bytes)
    font = instancer.instantiateVariableFont(font, {'FILL': 0, 'GRAD': 0, 'opsz': 24, 'wght': 400}, inplace=False)

    options = subset.Options()
    options.layout_features = ['rclt', 'rlig']    # How this font ligates names into icons
    options.glyph_names = True          # Keeps icon names readable in the font (the tests check them)
    options.layout_closure = False

    subsetter = subset.Subsetter(options)
    subsetter.populate(text=''.join(sorted(set(''.join(icons)))) + '_', glyphs=icons)
    subsetter.subset(font)

    out = io.BytesIO()
    font.recalcTimestamp = False    # makes output reproducible so --check can compare bytes
    font.flavor = 'woff2'
    font.save(out)

    return out.getvalue()


def build() -> dict[str, bytes]:

    files: dict[str, bytes] = {}

    files['InterVariable.woff2'] = download(text_font_file, text_font_SHA256).getvalue()
    files['LICENSE-inter-font.txt'] = download(text_font_license).getvalue()

    symbols = download(symbols_file, symbols_SHA256)

    icon_names = [g for g in TTFont(symbols).getGlyphOrder() if len(g) > 1 and re.fullmatch(r'[a-z0-9_]+', g)]

    icons = icons_used(icon_names)

    files['material-symbols-outlined.woff2'] = subset_symbols(symbols, icons)
    files['LICENSE-material-symbols.txt'] = download(symbols_license).getvalue()

    print(f'{len(icons)} icons kept: {" ".join(icons)}')

    header = f"""/*
 * Generated by tools/vendor_fonts.py.
 *
 * Inter font: commit {text_font_commit[:7]} (SIL OFL 1.1).
 * Material Symbols: commit {symbols_pinned_commit[:7]} (Apache 2.0).
 *
 * License files are alongside.
 */

"""

    text_font = """@font-face {
    font-family: 'Inter';
    font-style: normal;
    font-weight: 100 900;
    font-display: swap;
    src: url('InterVariable.woff2') format('woff2');
}

"""

    symbols_font = """@font-face {
    font-family: 'Material Symbols Outlined';
    font-style: normal;
    font-weight: 400;
    font-display: block;
    src: url('material-symbols-outlined.woff2') format('woff2');
}

.material-symbols-outlined {
    font-family: 'Material Symbols Outlined';
    font-weight: normal;
    font-style: normal;
    font-size: 24px;
    line-height: 1;
    letter-spacing: normal;
    text-transform: none;
    display: inline-block;
    white-space: nowrap;
    word-wrap: normal;
    direction: ltr;
    -webkit-font-smoothing: antialiased;
    -moz-osx-font-smoothing: grayscale;
    text-rendering: optimizeLegibility;
    font-feature-settings: 'liga';
}
"""

    files['fonts.css'] = (header + text_font + symbols_font).encode()

    return files


def main() -> None:

    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--check', action='store_true', help='just compare with the committed files instead of writing')
    args = parser.parse_args()

    files = build()

    if args.check:
        stale = [name for name, data in files.items() if not (OUT_DIR / name).is_file() or (OUT_DIR / name).read_bytes() != data]
        stale += [p.name for p in OUT_DIR.glob('*') if p.name not in files] if OUT_DIR.is_dir() else []

        if stale:
            sys.exit(f'Out of date: {", ".join(sorted(set(stale)))}. Run: uv run tools/vendor_fonts.py')
        print('Fonts are up to date.')

        return

    OUT_DIR.mkdir(parents=True, exist_ok=True)
    for name, data in files.items():
        (OUT_DIR / name).write_bytes(data)
        print(f'  {name}: {len(data) / 1024:.1f} KB')


if __name__ == '__main__':
    main()
